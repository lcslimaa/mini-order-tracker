CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK (role IN ('CLIENTE','OPERADOR'))
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 price DECIMAL(12,2) NOT NULL CHECK (price > 0),
 available BOOLEAN NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES app_users(id),
 address VARCHAR(1000) NOT NULL,
 status VARCHAR(32) NOT NULL CHECK (status IN ('RECEBIDO','EM_PREPARO','SAIU_PARA_ENTREGA','ENTREGUE','CANCELADO')),
 total DECIMAL(24,2) NOT NULL CHECK (total > 0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE TABLE order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id),
 name VARCHAR(160) NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL CHECK (unit_price > 0),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 subtotal DECIMAL(24,2) NOT NULL CHECK (subtotal > 0),
 UNIQUE(order_id,product_id)
);
CREATE INDEX idx_order_items_order ON order_items(order_id);
